// Layer 2 of the subject line generator: the pattern bank, and the retrieval that decides which
// thirty of its lines a given campaign's generator sees.
//
// Three kinds of line, none with a measured result (knowledge/subject-lines/README.md): pairs
// authored for the bank, real lines other brands sent (collected from Really Good Emails), and real
// lines the team imported from its own inboxes. So the bank carries range, not evidence, and
// retrieval optimises for range: the mechanisms the analysis recommends get most of the slots, but
// every other mechanism keeps one or two. Within each mechanism about half the slots go to real
// lines, so the generator always sees what senders actually wrote and not only what was written to
// teach it. Lines the team has banned never appear.
//
// Inside a mechanism, lines are ranked by how close they are in meaning to the brief when the
// semantic index is available (subject-line-semantic.js), and by tags and chance when it is not.
// Ranking by meaning alone would fill a mechanism's five slots with five ways of saying the same
// thing, so each next line is also penalised for resembling the ones already chosen. Meaning is
// about topic, so the campaign type still counts: a line from another brand's giveaway is a better
// model for a Westpack vote than a line that merely mentions gift boxes.

const { MECHANISM_KEYS, CAMPAIGN_TYPE_KEYS, TONE_KEYS, TRANSLATION_RISKS } = require("./subject-line-taxonomy");

let cachedBank = null;

// pattern-bank.json is generated by knowledge/subject-lines/tools/build-bank.js. A static require
// is what makes Vercel bundle it with the function.
function loadPatternBank() {
  if (cachedBank) return cachedBank;
  try {
    const bank = require("../../knowledge/subject-lines/pattern-bank.json");
    cachedBank = Array.isArray(bank?.entries) ? bank.entries : [];
  } catch (error) {
    cachedBank = [];
  }
  return cachedBank;
}

function isValidEntry(entry = {}) {
  return Boolean(
    String(entry.subject || "").trim()
    && Array.isArray(entry.mechanisms)
    && entry.mechanisms.length >= 1
    && entry.mechanisms.length <= 2
    && entry.mechanisms.every((key) => MECHANISM_KEYS.includes(key))
    && CAMPAIGN_TYPE_KEYS.includes(entry.campaignType)
    && TONE_KEYS.includes(entry.tone)
    && TRANSLATION_RISKS.includes(entry.translationRisk)
    // Authored entries are Danish or English; a line imported from a Swedish or German sender keeps
    // its own language code.
    && /^[a-z]{2,5}$/.test(String(entry.language || ""))
  );
}

// Deterministic for a given seed, so "generate" shows the same examples for the same campaign and
// "generate again" (a new seed) shows different ones.
function seededRandom(seed = "") {
  let state = 2166136261;
  for (const char of String(seed)) {
    state ^= char.charCodeAt(0);
    state = Math.imul(state, 16777619);
  }
  return () => {
    state = Math.imul(state ^ (state >>> 15), 2246822507);
    state = Math.imul(state ^ (state >>> 13), 3266489909);
    state ^= state >>> 16;
    return (state >>> 0) / 4294967296;
  };
}

function scoreEntry(entry, { campaignType, secondaryType }) {
  let score = 0;
  if (entry.campaignType === campaignType) score += 3;
  else if (secondaryType && entry.campaignType === secondaryType) score += 1.5;
  if (entry.language === "da") score += 2;
  if (entry.context === "westpack") score += 1;
  if (entry.translationRisk === "lav") score += 0.75;
  else if (entry.translationRisk === "hoej") score -= 0.5;
  if (entry.source === "imported") score += 2;
  return score;
}

function allocateSlots(recommended = [], limit = 30) {
  const ranked = [...new Set(recommended.filter((key) => MECHANISM_KEYS.includes(key)))];
  const rest = MECHANISM_KEYS.filter((key) => !ranked.includes(key));
  const slots = new Map();
  // The top recommendations carry the campaign; the others are there for range.
  const weights = [5, 4, 4, 3, 3, 2];
  ranked.forEach((key, index) => slots.set(key, weights[index] ?? 2));
  rest.forEach((key) => slots.set(key, 1));
  let total = [...slots.values()].reduce((sum, value) => sum + value, 0);
  const order = [...ranked, ...rest];
  while (total > limit) {
    const key = [...order].reverse().find((candidate) => slots.get(candidate) > (ranked.includes(candidate) ? 1 : 0));
    if (!key) break;
    slots.set(key, slots.get(key) - 1);
    total -= 1;
  }
  return slots;
}

const RELEVANCE_WINDOW = 40;
const REDUNDANCY_PENALTY = 0.4;
// On the scale of cosine similarity, where the closest lines to a brief sit around 0.4 to 0.7.
const SAME_TYPE_BONUS = 0.06;
const SECOND_TYPE_BONUS = 0.03;
const IMPORTED_BONUS = 0.03;

function relevanceScore(entry, relevance, { campaignType, secondaryType }) {
  const similarity = relevance.similarity.get(entry.id);
  if (similarity === undefined) return -1;
  let score = similarity;
  if (entry.campaignType === campaignType) score += SAME_TYPE_BONUS;
  else if (secondaryType && entry.campaignType === secondaryType) score += SECOND_TYPE_BONUS;
  if (entry.source === "imported") score += IMPORTED_BONUS;
  return score;
}

// Greedy maximal marginal relevance over the closest lines: each step takes the line most like the
// brief and least like what is already chosen, here or for an earlier mechanism - otherwise a vote
// brief gets a vote line in every mechanism. "Write new ones" moves on to the next lines in that
// order rather than drawing new ones at random.
function orderByRelevance(list, relevance, { context = {}, attempt = 0, take = 1, prior = [] } = {}) {
  const remaining = list
    .map((entry) => ({ entry, score: relevanceScore(entry, relevance, context) }))
    .sort((left, right) => right.score - left.score)
    .slice(0, RELEVANCE_WINDOW)
    .map((item) => ({ ...item, redundancy: prior.reduce((max, chosen) => Math.max(max, relevance.between(item.entry.id, chosen.id)), 0) }));
  const ordered = [];
  while (remaining.length) {
    let best = 0;
    remaining.forEach((item, index) => {
      if (item.score - REDUNDANCY_PENALTY * item.redundancy > remaining[best].score - REDUNDANCY_PENALTY * remaining[best].redundancy) best = index;
    });
    const [next] = remaining.splice(best, 1);
    ordered.push(next.entry);
    for (const item of remaining) item.redundancy = Math.max(item.redundancy, relevance.between(item.entry.id, next.entry.id));
  }
  const shift = ordered.length ? (attempt * take) % ordered.length : 0;
  return [...ordered.slice(shift), ...ordered.slice(0, shift)];
}

function selectBankExamples({ bank = loadPatternBank(), imported = [], banned = [], analysis = {}, limit = 30, seed = "", relevance = null, attempt = 0 } = {}) {
  const bannedIds = new Set(banned.map((item) => item.id).filter(Boolean));
  const pool = [...bank, ...imported].filter((entry) => !bannedIds.has(entry.id) && isValidEntry(entry));
  const recommended = (analysis.recommendedMechanisms || []).map((item) => item.mechanism || item);
  const avoided = new Set((analysis.avoidMechanisms || []).map((item) => item.mechanism || item));
  const slots = allocateSlots(recommended.filter((key) => !avoided.has(key)), limit);
  for (const key of avoided) slots.set(key, 0);

  const random = seededRandom(seed);
  const context = { campaignType: analysis.campaignType, secondaryType: analysis.secondaryType };
  const chosen = [];
  const used = new Set();
  const ranked = (list, take) => (relevance
    ? orderByRelevance(list, relevance, { context, attempt, take, prior: chosen })
    : list
      .map((entry) => ({ entry, score: scoreEntry(entry, context) + random() * 2.5 }))
      .sort((left, right) => right.score - left.score)
      .map((item) => item.entry));
  // An odd slot count leaves one slot over; it goes to a real line and a written one in turn, or
  // the many one-slot mechanisms would all go to real lines and the Danish patterns would vanish.
  let oddToReal = true;
  for (const [mechanism, count] of slots) {
    if (!count) continue;
    const forMechanism = pool.filter((entry) => entry.mechanisms[0] === mechanism && !used.has(entry.id));
    const real = ranked(forMechanism.filter((entry) => entry.source !== "authored"), count);
    const authored = ranked(forMechanism.filter((entry) => entry.source === "authored"), count);
    let half = Math.floor(count / 2);
    if (count % 2) {
      if (oddToReal) half += 1;
      oddToReal = !oddToReal;
    }
    const realSlots = Math.min(real.length, half);
    const picked = [...real.slice(0, realSlots), ...authored.slice(0, count - realSlots)];
    // Whichever pool runs short, the other fills the gap.
    if (picked.length < count) picked.push(...real.slice(realSlots, realSlots + count - picked.length));
    for (const entry of picked.slice(0, count)) {
      used.add(entry.id);
      chosen.push(entry);
    }
  }
  return chosen;
}

function summarizeBank(bank = loadPatternBank(), imported = []) {
  const count = (list, pick) => list.reduce((acc, entry) => {
    for (const key of [].concat(pick(entry))) acc[key] = (acc[key] || 0) + 1;
    return acc;
  }, {});
  return {
    authored: bank.filter((entry) => entry.source === "authored").length,
    collected: bank.filter((entry) => entry.source === "collected").length,
    collectedSenders: new Set(bank.filter((entry) => entry.source === "collected").map((entry) => entry.sender)).size,
    imported: imported.length,
    byMechanism: count([...bank, ...imported], (entry) => entry.mechanisms?.[0] || "unknown"),
    byLanguage: count([...bank, ...imported], (entry) => entry.language || "unknown"),
    byCampaignType: count([...bank, ...imported], (entry) => entry.campaignType || "unknown")
  };
}

function filterBank({ bank = loadPatternBank(), imported = [], mechanism = "", campaignType = "", language = "", source = "", query = "", limit = 200, offset = 0 } = {}) {
  const needle = String(query || "").trim().toLowerCase();
  const rows = [...imported, ...bank].filter((entry) => {
    if (mechanism && !entry.mechanisms?.includes(mechanism)) return false;
    if (campaignType && entry.campaignType !== campaignType) return false;
    if (language && entry.language !== language) return false;
    if (source && entry.source !== source) return false;
    if (needle && !`${entry.subject} ${entry.preview} ${entry.sender || ""}`.toLowerCase().includes(needle)) return false;
    return true;
  });
  return { total: rows.length, entries: rows.slice(offset, offset + limit) };
}

// Pasted lines from an inbox arrive in many shapes. One per line; "Subject — preview",
// "Subject | preview" or a tab between them all split into the pair.
function parseImportedLines(text = "", { max = 200 } = {}) {
  const seen = new Set();
  const rows = [];
  for (const raw of String(text || "").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    const parts = line.split(/\t| \| | — | – | -- /);
    const subject = String(parts.shift() || "").trim();
    const preview = parts.join(" ").trim();
    const key = subject.toLowerCase();
    if (!subject || subject.length > 150 || seen.has(key)) continue;
    seen.add(key);
    rows.push({ subject, preview });
    if (rows.length >= max) break;
  }
  return rows;
}

