// Layer 2 of the subject line generator: the pattern bank, and the retrieval that decides which
// thirty of its ~2,000 pairs a given campaign's generator sees.
//
// The bank is authored, not collected (knowledge/subject-lines/README.md says why), so it carries
// no evidence - only range. Retrieval therefore optimises for range: the mechanisms the analysis
// recommends get most of the slots, but every other mechanism keeps one or two, so the generator
// is shown a way of writing it would not have reached for on its own. Lines the team imported
// from real senders rank above authored ones, and lines the team has banned never appear.

const { MECHANISM_KEYS, CAMPAIGN_TYPE_KEYS, TONE_KEYS, TRANSLATION_RISKS } = require("./subject-line-taxonomy");

let cachedBank = null;

// pattern-bank.json is generated by knowledge/subject-lines/tools/build-bank.js. A static require
// is what makes Vercel bundle it with the function.
function loadPatternBank() {
  if (cachedBank) return cachedBank;
  try {
    const bank = require("../../knowledge/subject-lines/pattern-bank.json");
    cachedBank = Array.isArray(bank?.entries) ? bank.entries : [];
  } catch (error) {
    cachedBank = [];
  }
  return cachedBank;
}

function isValidEntry(entry = {}) {
  return Boolean(
    String(entry.subject || "").trim()
    && Array.isArray(entry.mechanisms)
    && entry.mechanisms.length >= 1
    && entry.mechanisms.length <= 2
    && entry.mechanisms.every((key) => MECHANISM_KEYS.includes(key))
    && CAMPAIGN_TYPE_KEYS.includes(entry.campaignType)
    && TONE_KEYS.includes(entry.tone)
    && TRANSLATION_RISKS.includes(entry.translationRisk)
    // Authored entries are Danish or English; a line imported from a Swedish or German sender keeps
    // its own language code.
    && /^[a-z]{2,5}$/.test(String(entry.language || ""))
  );
}

// Deterministic for a given seed, so "generate" shows the same examples for the same campaign and
// "generate again" (a new seed) shows different ones.
function seededRandom(seed = "") {
  let state = 2166136261;
  for (const char of String(seed)) {
    state ^= char.charCodeAt(0);
    state = Math.imul(state, 16777619);
  }
  return () => {
    state = Math.imul(state ^ (state >>> 15), 2246822507);
    state = Math.imul(state ^ (state >>> 13), 3266489909);
    state ^= state >>> 16;
    return (state >>> 0) / 4294967296;
  };
}

function scoreEntry(entry, { campaignType, secondaryType }) {
  let score = 0;
  if (entry.campaignType === campaignType) score += 3;
  else if (secondaryType && entry.campaignType === secondaryType) score += 1.5;
  if (entry.language === "da") score += 2;
  if (entry.context === "westpack") score += 1;
  if (entry.translationRisk === "lav") score += 0.75;
  else if (entry.translationRisk === "hoej") score -= 0.5;
  if (entry.source === "imported") score += 2;
  return score;
}

function allocateSlots(recommended = [], limit = 30) {
  const ranked = [...new Set(recommended.filter((key) => MECHANISM_KEYS.includes(key)))];
  const rest = MECHANISM_KEYS.filter((key) => !ranked.includes(key));
  const slots = new Map();
  // The top recommendations carry the campaign; the others are there for range.
  const weights = [5, 4, 4, 3, 3, 2];
  ranked.forEach((key, index) => slots.set(key, weights[index] ?? 2));
  rest.forEach((key) => slots.set(key, 1));
  let total = [...slots.values()].reduce((sum, value) => sum + value, 0);
  const order = [...ranked, ...rest];
  while (total > limit) {
    const key = [...order].reverse().find((candidate) => slots.get(candidate) > (ranked.includes(candidate) ? 1 : 0));
    if (!key) break;
    slots.set(key, slots.get(key) - 1);
    total -= 1;
  }
  return slots;
}

function selectBankExamples({ bank = loadPatternBank(), imported = [], banned = [], analysis = {}, limit = 30, seed = "" } = {}) {
  const bannedIds = new Set(banned.map((item) => item.id).filter(Boolean));
  const pool = [...bank, ...imported].filter((entry) => !bannedIds.has(entry.id) && isValidEntry(entry));
  const recommended = (analysis.recommendedMechanisms || []).map((item) => item.mechanism || item);
  const avoided = new Set((analysis.avoidMechanisms || []).map((item) => item.mechanism || item));
  const slots = allocateSlots(recommended.filter((key) => !avoided.has(key)), limit);
  for (const key of avoided) slots.set(key, 0);

  const random = seededRandom(seed);
  const context = { campaignType: analysis.campaignType, secondaryType: analysis.secondaryType };
  const chosen = [];
  const used = new Set();
  for (const [mechanism, count] of slots) {
    if (!count) continue;
    const candidates = pool
      .filter((entry) => entry.mechanisms[0] === mechanism && !used.has(entry.id))
      .map((entry) => ({ entry, score: scoreEntry(entry, context) + random() * 2.5 }))
      .sort((left, right) => right.score - left.score)
      .slice(0, count);
    for (const { entry } of candidates) {
      used.add(entry.id);
      chosen.push(entry);
    }
  }
  return chosen;
}

function summarizeBank(bank = loadPatternBank(), imported = []) {
  const count = (list, pick) => list.reduce((acc, entry) => {
    for (const key of [].concat(pick(entry))) acc[key] = (acc[key] || 0) + 1;
    return acc;
  }, {});
  return {
    authored: bank.length,
    imported: imported.length,
    byMechanism: count([...bank, ...imported], (entry) => entry.mechanisms?.[0] || "unknown"),
    byLanguage: count([...bank, ...imported], (entry) => entry.language || "unknown"),
    byCampaignType: count([...bank, ...imported], (entry) => entry.campaignType || "unknown")
  };
}

function filterBank({ bank = loadPatternBank(), imported = [], mechanism = "", campaignType = "", language = "", source = "", query = "", limit = 200, offset = 0 } = {}) {
  const needle = String(query || "").trim().toLowerCase();
  const rows = [...imported, ...bank].filter((entry) => {
    if (mechanism && !entry.mechanisms?.includes(mechanism)) return false;
    if (campaignType && entry.campaignType !== campaignType) return false;
    if (language && entry.language !== language) return false;
    if (source && entry.source !== source) return false;
    if (needle && !`${entry.subject} ${entry.preview} ${entry.sender || ""}`.toLowerCase().includes(needle)) return false;
    return true;
  });
  return { total: rows.length, entries: rows.slice(offset, offset + limit) };
}

// Pasted lines from an inbox arrive in many shapes. One per line; "Subject — preview",
// "Subject | preview" or a tab between them all split into the pair.
function parseImportedLines(text = "", { max = 200 } = {}) {
  const seen = new Set();
  const rows = [];
  for (const raw of String(text || "").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    const parts = line.split(/\t| \| | — | – | -- /);
    const subject = String(parts.shift() || "").trim();
    const preview = parts.join(" ").trim();
    const key = subject.toLowerCase();
    if (!subject || subject.length > 150 || seen.has(key)) continue;
    seen.add(key);
    rows.push({ subject, preview });
    if (rows.length >= max) break;
  }
  return rows;
}

