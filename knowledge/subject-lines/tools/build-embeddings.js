// Gives every line in the pattern bank a semantic fingerprint, so the writer is shown the lines that
// resemble the email at hand rather than lines picked by tag and chance.
//
//   node knowledge/subject-lines/tools/build-embeddings.js
//
// OpenAI text-embedding-3-small at 256 dimensions, quantised to one signed byte per dimension:
// 5,000 lines come to about 1.3 MB, small enough to ship with the function and load in a few
// milliseconds. Cosine similarity survives the quantisation to well within what ranking needs.
// Rebuild after build-bank.js; the ids are checked against the bank at load, so a stale file is
// ignored rather than misaligned.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..", "..");
process.chdir(ROOT);
const { getConfig } = require(path.join(ROOT, "server", "lib", "config"));
const { EMBEDDING_MODEL, EMBEDDING_DIMENSIONS, embedTexts, entryText, quantize } = require(path.join(ROOT, "server", "klaviyo", "subject-line-semantic"));

const BANK = require(path.join(__dirname, "..", "pattern-bank.json")).entries;
const OUT_BIN = path.join(__dirname, "..", "pattern-bank.vectors.bin");
const OUT_META = path.join(__dirname, "..", "pattern-bank.vectors.json");

async function build() {
  const config = getConfig();
  const data = new Int8Array(BANK.length * EMBEDDING_DIMENSIONS);
  for (let start = 0; start < BANK.length; start += 1000) {
    const batch = BANK.slice(start, start + 1000);
    const vectors = await embedTexts(config, batch.map(entryText));
    if (vectors.length !== batch.length) throw new Error(`Expected ${batch.length} vectors, got ${vectors.length}.`);
    vectors.forEach((vector, offset) => data.set(quantize(vector), (start + offset) * EMBEDDING_DIMENSIONS));
    console.log(`embedded ${Math.min(start + 1000, BANK.length)}/${BANK.length}`);
  }
  fs.writeFileSync(OUT_BIN, Buffer.from(data.buffer));
  fs.writeFileSync(OUT_META, `${JSON.stringify({
    note: "Generated by knowledge/subject-lines/tools/build-embeddings.js. Row i of pattern-bank.vectors.bin (dimensions signed bytes, direction only) is ids[i].",
    model: EMBEDDING_MODEL,
    dimensions: EMBEDDING_DIMENSIONS,
    builtAt: new Date().toISOString(),
    count: BANK.length,
    ids: BANK.map((entry) => entry.id)
  })}\n`);
  console.log(`wrote ${(data.length / 1024 / 1024).toFixed(2)} MB of vectors for ${BANK.length} lines`);
}

build().catch((error) => {
  console.error(error);
  process.exit(1);
});
